'use strict';

// C-18: suppressions and justification comments in the diff become findings.
// C-26: any other new comment in product code is a blocking finding.

const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { isBlockingFinding } = require('../lib/orchestration.js');
const { commentOf, scanComments, scanRunComments, mergeCommentFindings } = require('../lib/comment-findings.js');

const diff = (file, lines) => `diff --git a/${file} b/${file}\n--- a/${file}\n+++ b/${file}\n@@ -1 +1,${lines.length} @@\n${lines.map((l) => `+${l}`).join('\n')}\n`;

test('AC-1 an unexplained eslint-disable is a HIGH finding at file:line; a reasoned one is MEDIUM', () => {
  const [bare] = scanComments(diff('src/a.ts', ['const x = 1;', '// eslint-disable-next-line no-explicit-any']));
  assert.strictEqual(bare.severity, 'HIGH');
  assert.strictEqual(bare.location, 'src/a.ts:2');
  assert.strictEqual(bare.axis, 'standards');
  assert.match(bare.concreteAlternativeDiff, /remove the suppression/);
  const [reasoned] = scanComments(diff('src/a.ts', ['// eslint-disable-next-line no-explicit-any -- third-party typings are wrong, tracked in #42']));
  assert.strictEqual(reasoned.severity, 'MEDIUM');
  for (const [file, line] of [['src/b.ts', '// @ts-ignore'], ['src/b.py', 'x = f()  # type: ignore'], ['src/b.py', 'import os  # noqa'], ['src/b.js', '/* istanbul ignore next */']]) {
    const found = scanComments(diff(file, [line]));
    assert.strictEqual(found.length, 1, line);
    assert.strictEqual(found[0].severity, 'HIGH', line);
  }
});

test('justification comments are MEDIUM; plain "why" comments, tests and docs are ignored', () => {
  const [work] = scanComments(diff('src/a.js', ['setTimeout(fix, 0); // quick fix until the store is declarative']));
  assert.strictEqual(work.severity, 'MEDIUM');
  assert.match(work.failureScenario, /justifies a workaround/);
  assert.deepStrictEqual(scanComments(diff('src/a.js', ['// Retries cap at 3 because the upstream API rate-limits at 5/s']), { noComments: false }), []);
  assert.deepStrictEqual(scanComments(diff('tests/a.test.js', ['// eslint-disable-next-line'])), []);
  assert.deepStrictEqual(scanComments(diff('docs/guide.md', ['a temporary workaround'])), []);
  assert.deepStrictEqual(scanComments(diff('src/a.js', ["const label = 'quick fix';"])), [], 'not a comment');
});

test('AC-3 projects can add their own justification patterns', () => {
  const extra = [/\bbypass the guard\b/i];
  assert.strictEqual(scanComments(diff('src/a.js', ['// bypass the guard here']), { extraPatterns: extra }).length, 1);
});

test('reviewers may dismiss a comment finding only with evidence', () => {
  const [item] = scanComments(diff('src/a.ts', ['// @ts-ignore']));
  assert.strictEqual(mergeCommentFindings({ findings: [] }, [item]).added, 1);
  assert.match(mergeCommentFindings({ findings: [{ ...item, validity: 'INVALID' }] }, [item]).errors[0], /without dismissal\.evidence/);
  const ok = { findings: [{ ...item, validity: 'INVALID', dismissal: { by: 'da', evidence: 'generated file from openapi; regenerated each build' } }] };
  assert.deepStrictEqual(mergeCommentFindings(ok, [item]).errors, []);
});

test('C-26 plain comments in product code are one blocking hard-convention finding per file', () => {
  const found = scanComments(diff('src/a.js', ['// Retries cap at 3', 'const n = 3;', 'f(); // call f', '/**', ' * Docs.', ' */']));
  assert.strictEqual(found.length, 1);
  const [item] = found;
  assert.strictEqual(item.source, 'no-comments');
  assert.strictEqual(item.hardConvention, true);
  assert.strictEqual(item.severity, 'HIGH');
  assert.strictEqual(item.axis, 'standards');
  assert.strictEqual(item.location, 'src/a.js:1');
  assert.match(item.evidence, /comment lines 1, 3, 4, 5, 6/);
  assert.match(item.concreteAlternativeDiff, /delete it/);
  assert.strictEqual(isBlockingFinding(item), true, 'the Judge must ITERATE on it');
  assert.strictEqual(scanComments(diff('src/b.py', ['x = 1  # note'])).length, 1);
});

test('C-26 tooling, legal, test, doc and string content is not a comment finding', () => {
  const allowed = ['#!/usr/bin/env node', '// SPDX-License-Identifier: MIT', '/// <reference types="node" />', '// @generated by protoc', '//go:build linux'];
  for (const line of allowed) assert.deepStrictEqual(scanComments(diff('src/a.js', [line])), [], line);
  assert.deepStrictEqual(scanComments(diff('src/a.go', ['//go:build linux'])), []);
  assert.deepStrictEqual(scanComments(diff('src/a.sh', ['#!/bin/sh'])), []);
  assert.deepStrictEqual(scanComments(diff('tests/a.test.js', ['// arrange'])), []);
  assert.deepStrictEqual(scanComments(diff('README.md', ['# Title'])), []);
  assert.deepStrictEqual(scanComments(diff('config.yml', ['# setting'])), []);
  for (const line of ['const url = "http://example.com";', 'class A { #secret = 1 }', 'const tag = "#x";', 'const a = b * c;', 'const re = /a\\/b/;']) {
    assert.strictEqual(commentOf('src/a.ts', line), null, line);
  }
  assert.strictEqual(commentOf('src/a.py', 's = "#tag"'), null);
});

test('C-26 suppressions and justifications are not double counted as plain comments', () => {
  const found = scanComments(diff('src/a.ts', ['// @ts-ignore', 'x(); // quick fix for now']));
  assert.deepStrictEqual(found.map((item) => item.source), ['comment-justification', 'comment-justification']);
});

test('C-26 a project opts out with "comments": "allow" in rules.json', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ael-nocomment-'));
  fs.mkdirSync(path.join(root, '.ai-engineering-loop'));
  fs.writeFileSync(path.join(root, 'change.diff'), diff('src/a.js', ['// why this exists']));
  const run = { artifacts: { diff: { path: 'change.diff' } } };
  assert.strictEqual(scanRunComments(root, run).length, 1);
  fs.writeFileSync(path.join(root, '.ai-engineering-loop', 'rules.json'), JSON.stringify({ comments: 'allow' }));
  assert.deepStrictEqual(scanRunComments(root, run), []);
});

test('C-26 removing hardConvention or the severity needs dismissal evidence', () => {
  const [item] = scanComments(diff('src/a.js', ['// note']));
  assert.match(mergeCommentFindings({ findings: [{ ...item, hardConvention: false }] }, [item]).errors[0], /without dismissal\.evidence/);
  assert.match(mergeCommentFindings({ findings: [{ ...item, severity: 'LOW' }] }, [item]).errors[0], /without dismissal\.evidence/);
});
