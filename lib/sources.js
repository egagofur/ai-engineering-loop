'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const { redactHomePaths, redactSecrets } = require('./safe-context.js');
const { gitReadiness } = require('./git-readiness.js');

const SOURCES_FILE = path.join('.ai-engineering-loop', 'sources.md');
const GATHER_BUDGET = Object.freeze({ T0: 0, T1: 4, T2: 8 });
const SCOPE_HEADING = '## Scope (edit me)';
const MAX_LINE = 200;

const home = () => process.env.HOME || process.env.USERPROFILE || os.homedir();
const fail = (message, code, extra = {}) => Object.assign(new Error(message), { code, ...extra });

function runTool(bin, args, cwd) {
  const command = bin.endsWith('.js') ? process.execPath : bin;
  const argv = bin.endsWith('.js') ? [bin, ...args] : args;
  const result = spawnSync(command, argv, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 10000 });
  return { installed: !(result.error && result.error.code === 'ENOENT'), ok: result.status === 0, out: `${result.stdout || ''}` };
}

function readText(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch {
    return '';
  }
}

function remotes(rootDir) {
  return runTool('git', ['remote', '-v'], rootDir).out;
}

function mattermostConfigs(rootDir, base) {
  const candidates = [
    path.join(base, '.claude.json'),
    path.join(base, '.claude', 'settings.json'),
    path.join(base, '.cursor', 'mcp.json'),
    path.join(base, '.codex', 'config.toml'),
    path.join(base, '.gemini', 'settings.json'),
    path.join(base, '.gemini', 'antigravity', 'mcp_config.json'),
    path.join(rootDir, '.mcp.json'),
    path.join(rootDir, '.cursor', 'mcp.json')
  ];
  return candidates.filter((file) => /mattermost/i.test(readText(file))).map((file) => redactHomePaths(file));
}

function aelHistory(rootDir) {
  const dir = path.join(rootDir, '.ai-engineering-loop');
  let runs = 0;
  try {
    runs = fs.readdirSync(path.join(dir, 'runs')).filter((name) => name !== 'current.json').length;
  } catch {
    runs = 0;
  }
  const parts = [];
  if (runs) parts.push(`${runs} past Run(s)`);
  for (const name of ['lessons.md', 'debt.json', 'feature-map.md', 'transcript-lessons.json']) {
    if (fs.existsSync(path.join(dir, name))) parts.push(name);
  }
  return parts;
}

function detectSources(rootDir, { homeDir = home() } = {}) {
  const git = gitReadiness(rootDir);
  const remoteText = git.ok ? remotes(rootDir) : '';
  const gh = runTool(process.env.AEL_GH_BIN || 'gh', ['auth', 'status'], rootDir);
  const glab = runTool(process.env.AEL_GLAB_BIN || 'glab', ['auth', 'status'], rootDir);
  const mattermost = mattermostConfigs(rootDir, homeDir);
  const history = aelHistory(rootDir);
  const status = (tool) => (!tool.installed ? 'not installed' : tool.ok ? 'logged in' : 'installed, not logged in');
  return [
    { id: 'code', label: 'Code and git history', available: git.ok, detail: git.ok ? 'git log, git blame, rg' : git.message, try: 'rg -n "<term>"; git log -S "<term>" --oneline -n 5' },
    { id: 'github', label: 'GitHub issues and PRs', available: gh.ok, detail: `gh ${status(gh)}${/github\.com/.test(remoteText) ? ', GitHub remote' : ''}`, try: 'gh issue list --search "<term>" -L 5; gh pr list --search "<term>" --state all -L 5' },
    { id: 'gitlab', label: 'GitLab issues and MRs', available: glab.ok, detail: `glab ${status(glab)}${/gitlab/.test(remoteText) ? ', GitLab remote' : ''}`, try: 'glab issue list --search "<term>"; glab mr list --search "<term>"' },
    { id: 'mattermost', label: 'Mattermost (read-only MCP)', available: mattermost.length > 0, detail: mattermost.length ? `MCP configured in ${mattermost.join(', ')}` : 'no Mattermost MCP found in host configs', try: 'Mattermost-Agent MCP read/search tools only, within the channels listed under Scope; never post' },
    { id: 'ael', label: 'AEL history', available: history.length > 0, detail: history.length ? history.join(', ') : 'nothing yet', try: 'ai-engineering-loop learn; ai-engineering-loop debt list' }
  ];
}

function existingScope(text) {
  const start = text.indexOf(SCOPE_HEADING);
  return start === -1 ? null : text.slice(start).trimEnd();
}

function renderSources(sources, scope) {
  const rows = sources.map((item) => `| ${item.id} | ${item.available ? 'yes' : 'no'} | ${item.label} | ${item.detail} | \`${item.try}\` |`);
  return [
    '# Sources the agent may read before asking you',
    '',
    'Generated by `ai-engineering-loop init`, `refresh` and `sources refresh`. The table is rewritten; the Scope section below is yours and is kept.',
    '',
    'Rules: read-only. Dig in these sources before asking the human. Per-Run budget: T0 0, T1 4, T2 8 gather queries (`sources record`). A Goal Contract fact must cite a source the CLI can check (`path:line`, commit, or a recorded `S-n`).',
    '',
    '| Source | Available | What | Detail | Try |',
    '|---|---|---|---|---|',
    ...rows,
    '',
    scope || `${SCOPE_HEADING}\n\n- Mattermost channels: <none yet; list channel names the agent may read>\n- Issue labels or projects: <optional>\n- Never read: <optional>`,
    ''
  ].join('\n');
}

function writeSourcesFile(rootDir, options = {}) {
  const file = path.join(rootDir, SOURCES_FILE);
  const sources = detectSources(rootDir, options);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, renderSources(sources, existingScope(readText(file))));
  return { path: SOURCES_FILE.split(path.sep).join('/'), sources };
}

function sourcesPath(rootDir, runId) {
  return path.join(rootDir, '.ai-engineering-loop', 'runs', runId, 'sources.json');
}

function loadGathered(rootDir, runId) {
  try {
    const value = JSON.parse(fs.readFileSync(sourcesPath(rootDir, runId), 'utf8'));
    return Array.isArray(value.entries) ? value.entries : [];
  } catch {
    return [];
  }
}

const clean = (text) => {
  const value = redactHomePaths(redactSecrets(String(text || '')).text).replace(/\s+/g, ' ').trim();
  return value.length > MAX_LINE ? `${value.slice(0, MAX_LINE - 1)}…` : value;
};

function recordGather(rootDir, run, { source, ref, line }) {
  if (!String(source || '').trim() || !String(ref || '').trim() || !String(line || '').trim()) {
    throw fail('sources record needs --source, --ref and --line', 'INVALID_USAGE', { why: 'Each gathered fact keeps where it came from and one line of what it says.', fix: '`sources record --run <id> --source github --ref https://github.com/o/r/issues/12 --line "Export must respect filters"`' });
  }
  const tier = run.tier?.current || 'T1';
  const budget = GATHER_BUDGET[tier] ?? GATHER_BUDGET.T1;
  const entries = loadGathered(rootDir, run.runId);
  if (entries.length >= budget) {
    throw fail(`Gather budget for ${tier} is ${budget} quer${budget === 1 ? 'y' : 'ies'}; ${entries.length} already recorded`, 'GATHER_BUDGET', {
      why: 'Digging without a limit burns tokens; past the budget, asking the human one question is cheaper.',
      fix: tier === 'T2' ? 'Stop gathering; mark the remaining statements as assumptions or ask the human one question.' : 'Stop gathering; mark the rest as assumptions, ask the human, or re-tier with `run --tier T2 --tier-reason "<why>"` if the task is bigger.'
    });
  }
  const entry = { id: `S-${entries.length + 1}`, source: clean(source), ref: clean(ref), line: clean(line), at: new Date().toISOString() };
  const next = [...entries, entry];
  fs.writeFileSync(sourcesPath(rootDir, run.runId), `${JSON.stringify({ schemaVersion: 1, runId: run.runId, budget, entries: next }, null, 2)}\n`, { mode: 0o600 });
  return { entry, used: next.length, budget };
}

function gatherHints(rootDir, run) {
  const tier = run?.tier?.current || 'T1';
  const terms = [...new Set(String(run?.task || '').toLowerCase().split(/[^a-z0-9_-]+/).filter((word) => word.length >= 4))].slice(0, 3);
  const term = terms[0] || '<term>';
  const sources = detectSources(rootDir).filter((item) => item.available);
  return {
    tier,
    budget: GATHER_BUDGET[tier] ?? GATHER_BUDGET.T1,
    used: run ? loadGathered(rootDir, run.runId).length : 0,
    terms,
    hints: sources.map((item) => ({ source: item.id, try: item.try.replace(/<term>/g, term) }))
  };
}

module.exports = { GATHER_BUDGET, SOURCES_FILE, detectSources, gatherHints, loadGathered, recordGather, renderSources, writeSourcesFile };
